"""Generate firmware/mindmirror_necklace/clips.h: short phrases stored in the
necklace so it can always speak through its own speaker, even when the phone
is unreachable. These are clearly fallback lines, never AI replies.

Needs: pip install kokoro-onnx soundfile numpy
and the two model files from
https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0
(kokoro-v1.0.int8.onnx, voices-v1.0.bin) next to this script.

Run: python make_clips.py
"""
import os
import numpy as np
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "mindmirror_necklace", "clips.h")
VOICE = "af_heart"
RATE = 16000

# Order must match enum LocalClip in protocol.h.
PHRASES = [
    ("HELLO", "Hi, I'm your MindMirror. Hold the button and tell me how you feel."),
    ("NO_PHONE", "I can't reach your phone right now. Please open MindMirror and keep Bluetooth on."),
    ("RETRY", "Sorry, I didn't catch that. Could you say it again?"),
    ("TEST", "Speaker test. If you can hear this, my speaker works."),
    ("LOW_BATTERY", "My battery is getting low. Please charge me soon."),
    ("ON_SCREEN", "I've put my answer on your phone screen."),
]

STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97,
        107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796,
        876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871,
        5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623,
        27086, 29794, 32767]
INDEX = [-1, -1, -1, -1, 2, 4, 6, 8]


def adpcm(pcm):
    pred, index, out = 0, 0, bytearray()
    nibs = []
    for s in pcm:
        step = STEP[index]
        diff = int(s) - pred
        nib = 0
        if diff < 0:
            nib, diff = 8, -diff
        vp = step >> 3
        if diff >= step:
            nib |= 4; diff -= step; vp += step
        step >>= 1
        if diff >= step:
            nib |= 2; diff -= step; vp += step
        step >>= 1
        if diff >= step:
            nib |= 1; vp += step
        pred = max(-32768, min(32767, pred - vp if nib & 8 else pred + vp))
        index = max(0, min(88, index + INDEX[nib & 7]))
        nibs.append(nib)
    if len(nibs) % 2:
        nibs.append(0)
    for i in range(0, len(nibs), 2):
        out.append(nibs[i] | (nibs[i + 1] << 4))
    return bytes(out)


def resample(x, src, dst):
    # Low-pass (windowed sinc at 0.45 * dst) then linear-phase decimation.
    taps = 63
    fc = 0.45 * dst / src
    n = np.arange(taps) - (taps - 1) / 2
    h = np.sinc(2 * fc * n) * np.hamming(taps)
    h /= h.sum()
    y = np.convolve(x, h, mode="same")
    t = np.arange(0, len(y) * dst / src) * src / dst
    return np.interp(t, np.arange(len(y)), y)


def main():
    k = Kokoro(os.path.join(HERE, "kokoro-v1.0.int8.onnx"), os.path.join(HERE, "voices-v1.0.bin"))
    lines = ["// Generated by firmware/tools/make_clips.py. Do not edit by hand.",
             "// 16 kHz mono IMA ADPCM, voice: Kokoro " + VOICE + ".", "#pragma once", "#include <stdint.h>", ""]
    table = []
    for name, text in PHRASES:
        samples, sr = k.create(text, voice=VOICE, speed=1.0, lang="en-us")
        x = resample(np.asarray(samples, dtype=np.float64), sr, RATE)
        x = x / (np.abs(x).max() + 1e-9) * 0.89  # about -1 dBFS
        pad = np.zeros(int(0.08 * RATE))
        pcm = np.clip(np.concatenate([pad, x, pad]) * 32767, -32768, 32767).astype(np.int16)
        data = adpcm(pcm)
        lines.append(f"// {name}: \"{text}\" ({len(pcm) / RATE:.1f} s)")
        lines.append(f"static const uint8_t CLIP_{name}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        table.append((name, len(data)))
        print(f"{name}: {len(pcm) / RATE:.1f} s, {len(data)} bytes")
    lines.append("")
    lines.append("struct LocalClipData { const uint8_t* data; uint32_t bytes; };")
    lines.append("static const LocalClipData LOCAL_CLIPS[] = {")
    for name, n in table:
        lines.append(f"  {{CLIP_{name}, {n}}},")
    lines.append("};")
    lines.append(f"static const uint8_t LOCAL_CLIP_COUNT = {len(table)};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
